// Scan apps/mobile/assets/audio/*.mp3 → apps/mobile/src/audio/manifest.ts (static requires so Metro bundles them).
// Run after tools/tts-batch.ts or tools/audio-fetch.mjs. Idempotent.
import { readdirSync, writeFileSync, mkdirSync, existsSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const dir = resolve(root, "apps/mobile/assets/audio");
mkdirSync(dir, { recursive: true });
const files = readdirSync(dir).filter((f) => f.endsWith(".mp3")).sort();
const lines = files.map((f) => `  ${JSON.stringify(f)}: require("../../assets/audio/${f}"),`);
// which voice these files came from (audio-fetch writes it), so Parent Corner can show it and a stale folder is visible
const lockPath = resolve(dir, "urls.lock.json");
const voice = (existsSync(lockPath) ? JSON.parse(readFileSync(lockPath, "utf8"))._voice : undefined) ?? (files.length ? "unknown" : "device");
const out = `// Generated by tools/audio-manifest.mjs — do not edit. ${files.length} pre-rendered lines.\n/* eslint-disable @typescript-eslint/no-require-imports */\nexport const VOICE = ${JSON.stringify(voice)};\nexport const AUDIO: Record<string, number> = {\n${lines.join("\n")}\n};\n`;
writeFileSync(resolve(root, "apps/mobile/src/audio/manifest.ts"), out);
console.log(`manifest: ${files.length} audio files (voice: ${voice})`);
